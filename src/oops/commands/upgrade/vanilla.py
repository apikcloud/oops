@dataclass
class VanillaModule:
    name: str
    classification: str
    location: str
    load_index: int
    submodule: "Optional[str]" = None
    # Submodule's rel_path (Addon.rel_path == the git Submodule's own .path,
    # both keyed the same way in services.git.list_submodules) — the only
    # reliable key to find the actual Submodule object back later, since a
    # submodule's .name is whatever it was created with (an "owner/repo"
    # slug for submodules added via `oops submodules add`, but a bare path
    # for one added directly via `git submodule add`) and cannot be derived
    # from itself by splitting on "/".
    rel_path: str = ""
    # The addon's own directory name (Path(Addon.path).name). Used by
    # `build_strip_plan` to catch a submodule checked out directly at the
    # repo root (no `.third-party` nesting): such an addon has `rel_path ==
    # ""` (its manifest sits at the submodule's own root), so it cannot be
    # matched to its submodule via `rel_path` the way a nested one is — its
    # directory name has to be checked against every submodule's `.path`
    # instead.
    dir_name: str = ""
    # Set by `flag_kb_collisions` when this "addon" is actually a real Odoo
    # module (core or enterprise) that shouldn't be in the project repo at
    # all. It is still removed either way — this only changes the warning
    # and the report, never whether the module is stripped.
    matched_origin: "Optional[str]" = None


@dataclass
class VanillaReport:
    from_version: str
    to_version: str
    modules: "list[VanillaModule]"
    script_path: str
    branch: "Optional[str]" = None
    image: "Optional[str]" = None
    synced_files: "list[str]" = field(default_factory=list)
    orphan_submodules: "list[str]" = field(default_factory=list)
    generated_at: str = ""
    kb_checked: bool = False

    def __post_init__(self):
        if not self.generated_at:
            self.generated_at = datetime.now(UTC).isoformat()


def discover_non_core_addons(repo_path: Path, sub_meta_by_relpath: dict) -> "list[Addon]":
    """Discover and classify every addon at the repo root.

    Thin filter over `oops_engine.addons.discover_addons` — the one discovery
    pipeline shared with `addons list` and `upgrade analyze`. Every addon it
    returns is non-core by construction: Odoo core is never checked into this
    repo.
    """
    return [
        addon
        for addon in discover_addons(
            repo_path,
            sub_meta_by_relpath,
            author=config.manifest.author,
            prefix=config.project.prefix,
            owner=config.github.owner,
            shallow=True,
        )
        if addon.root
    ]


def load_installed_context(
    repo_path: Path, addons: "list[Addon]", from_version: str, kb_modules: "Optional[dict]" = None
) -> "tuple[dict[str, list[str]], list[str]]":
    """Resolve real dependency data for modules `compute_removal_order` needs
    to see but that aren't among the discovered non-core addons — i.e. the
    Odoo core/enterprise/already-installed modules a custom addon depends on.

    Without this, a custom addon whose manifest ``depends`` lists only core
    modules (e.g. ``sale``, ``account`` — never checked into the repo, so
    never in the discovered set) has no in-`installed` dependency at all and
    gets ``load_index=0`` like every other such addon: safe (nothing
    among the removed modules depends on it either), but uninformative, and
    not what the generated script's own comment claims ("position in the
    forward Odoo registry load order").

    Reads `installed_modules.txt` (the project's authoritative "what's
    actually installed in the target database" list — the same file
    `oops refactor`/`oops misc build-kb --installed-only` already rely on)
    and looks up each entry not already a discovered addon in the global
    Odoo KB for `from_version` to get its real `depends`.

    Returns (extra_depends, warnings): `extra_depends` maps each such module
    name to its KB-recorded depends list — merge into `compute_removal_order`'s
    graph, never into the removed-modules list itself. Degrades gracefully
    (returns `({}, [<one warning>])`) when installed_modules.txt is absent,
    same contract as `flag_kb_collisions` for a missing global KB.

    `kb_modules` lets the caller pass in a KB already loaded via
    `load_odoo_kb(from_version)` (as `flag_kb_collisions` also needs) instead
    of loading it again here.
    """
    info = read_installed_modules(repo_path)
    warnings: "list[str]" = []
    file_name = config.project.file_installed_modules

    if info is None:
        warnings.append(
            f"{file_name} not found — load order only reflects dependencies between the discovered "
            f"non-core modules themselves, not their real position in the Odoo registry. Create it "
            "(one module name per line) for a fully-resolved order."
        )
        return {}, warnings

    missing_at_root, extra_at_root = compute_root_drift(repo_path, info.modules)
    if missing_at_root:
        warnings.append(
            f"{file_name} lists module(s) with no addon at the repo root "
            f"(assumed Odoo core/enterprise, not project-owned): {', '.join(missing_at_root)}"
        )
    if extra_at_root:
        warnings.append(
            f"Addon(s) at the repo root not listed in {file_name} (will still be removed): {', '.join(extra_at_root)}"
        )

    discovered_names = {a.technical_name for a in addons}
    if kb_modules is None:
        kb_modules = load_odoo_kb(from_version)
    extra_depends: "dict[str, list[str]]" = {}
    unresolved: "list[str]" = []
    for name in info.modules:
        if name in discovered_names:
            continue
        entry = kb_modules.get(name)
        if entry is None:
            unresolved.append(name)
            continue
        extra_depends[name] = entry.get("depends", [])

    if unresolved:
        warnings.append(
            f"{len(unresolved)} module(s) in {file_name} have no record in the global Odoo KB for "
            f"{from_version!r} — their dependency chain stops there: {', '.join(sorted(unresolved))}"
        )

    return extra_depends, warnings


def compute_removal_order(
    addons: "list[Addon]", extra_depends: "Optional[dict[str, list[str]]]" = None
) -> "list[VanillaModule]":
    """Order addons for safe uninstall: dependents before their dependencies.

    Reuses `oops_engine.load_order.compute_load_order` — the same algorithm
    that reproduces Odoo's own registry load order. `extra_depends` (from
    `load_installed_context`) extends the graph with the real modules a
    discovered addon depends on but that aren't discovered addons themselves
    (core, or already-installed OCA/third-party) — without it, ordering is
    restricted to the tiny subgraph of addons that depend on each other
    directly. Either way, unresolvable deps are silently dropped by
    `compute_load_order`, which is exactly what we want here. Sorting the
    result *descending* by load_index gives the reverse load order: modules
    loaded last (i.e. the most dependent) are removed first.
    """
    installed = {a.technical_name for a in addons}
    depends = {a.technical_name: a.depends for a in addons}
    if extra_depends:
        installed |= set(extra_depends)
        depends.update(extra_depends)

    try:
        order = compute_load_order(installed, depends)
    except RecursionError as exc:
        raise OopsError(
            "Dependency cycle detected among project addons — cannot compute a safe uninstall order."
        ) from exc

    by_name = {a.technical_name: a for a in addons}
    ranked = sorted(
        ((name, load_index) for name, (_depth, load_index) in order.items() if name in by_name),
        key=lambda item: item[1],
        reverse=True,
    )
    return [
        VanillaModule(
            name=name,
            classification=by_name[name].classification or "",
            location=by_name[name].location,
            load_index=load_index,
            submodule=by_name[name].submodule or None,
            rel_path=by_name[name].rel_path,
            dir_name=Path(by_name[name].path).name,
        )
        for name, load_index in ranked
    ]


def flag_kb_collisions(
    modules: "list[VanillaModule]", from_version: str, kb_modules: "Optional[dict]" = None
) -> "tuple[bool, list[str]]":
    """Cross-check every module against the global Odoo KB for `from_version`.

    Any module whose technical name matches a real Odoo core/enterprise
    module (per `services.kb.load_odoo_kb`) is annotated in place
    (`module.matched_origin`) and a warning string is returned for it —
    it is NOT removed from `modules`; the caller still strips it.

    Returns (kb_checked, warnings): `kb_checked` is False if the global KB
    for `from_version` was never built (`load_odoo_kb` returns `{}` in that
    case, per its own documented graceful-degradation contract — this is
    not an error, just a weaker guarantee, surfaced as one extra warning).

    `kb_modules` lets the caller pass in a KB already loaded via
    `load_odoo_kb(from_version)` (as `load_installed_context` also needs)
    instead of loading it again here.
    """
    if kb_modules is None:
        kb_modules = load_odoo_kb(from_version)
    warnings: "list[str]" = []

    if not kb_modules:
        warnings.append(
            f"Global Odoo KB not found for version {from_version!r} — core/enterprise collision "
            f"detection skipped. Run `oops misc build-kb --version {from_version}` first for full detection."
        )
        return False, warnings

    for m in modules:
        entry = kb_modules.get(m.name)
        if entry is None:
            continue
        origin = normalize_origin(entry.get("origin")) or "core"
        m.matched_origin = origin
        warnings.append(
            f"'{m.name}' is classified as {m.classification!r} but matches a real Odoo {origin} "
            "module in the global KB — likely committed by mistake. It will still be removed."
        )

    return True, warnings


def render_uninstall_script(modules: "list[VanillaModule]") -> str:
    lines = "\n".join(f'    ("{m.name}", {m.load_index}),' for m in modules)
    return UNINSTALL_SCRIPT_TEMPLATE.format(
        generated_at=datetime.now(UTC).isoformat(),
        dotless_models=", ".join(f'"{m}"' for m in config.upgrade.dotless_models),
        module_lines=lines,
        script_path=SCRIPT_REL_PATH,
    )


def write_uninstall_script(repo_path: Path, content: str, dry_run: bool = False) -> Path:
    script_path = repo_path / SCRIPT_REL_PATH
    if dry_run:
        return script_path
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(content, encoding="utf-8")
    return script_path


def save_vanilla_report(path: Path, report: VanillaReport) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(asdict(report), sort_keys=False), encoding="utf-8")


