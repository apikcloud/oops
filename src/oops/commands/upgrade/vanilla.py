def ensure_upgrade_util_requirement(repo_path: Path, dry_run: bool = False) -> Path:
    """Overwrite requirements.txt with only the upgrade-util pip line.

    Unlike `ensure_git_package` for packages.txt (a user-curated OS-package
    list, unrelated to addons), requirements.txt is addon-derived — and every
    addon is being stripped. Whatever is already there (e.g. a file just
    written by `sync_project_files`) belongs to modules that no longer exist
    in this tree, so it is discarded rather than merged into. Not derived via
    `io/requirements.generate_requirements` either (same reason: it builds its
    output purely from addon manifests, none of which remain). A later
    `oops requirements update` run on this branch will regenerate the file
    from whatever addons exist at that point and will drop this line unless
    re-added — a known limitation, not fixed here.
    """
    req_path = repo_path / config.project.file_requirements
    if dry_run:
        return req_path
    req_path.write_text(f"# generated by `oops upgrade vanilla`\n{UPGRADE_UTIL_REQUIREMENT}\n", encoding="utf-8")
    return req_path


def ensure_git_package(repo_path: Path, dry_run: bool = False) -> Path:
    """Ensure `git` is listed in packages.txt.

    pip's `git+https://...` VCS syntax (used for the upgrade-util
    requirement above) shells out to the system `git` binary at install
    time — if the project's image doesn't install it, `pip install -r
    requirements.txt` fails there. Unlike requirements.txt, packages.txt is
    a user-curated OS-package list, not addon-derived, so this merges "git"
    into whatever is already present rather than overwriting the file.
    """
    packages_path = repo_path / config.project.file_packages
    existing = parse_packages(repo_path) if packages_path.exists() else []
    if "git" in existing or dry_run:
        return packages_path
    write_text_file(packages_path, sorted({*existing, "git"}))
    return packages_path


# ---------------------------------------------------------------------------
# Bump to target version / sync project scaffolding
# ---------------------------------------------------------------------------


def bump_odoo_version(repo_path: Path, to_version: str, dry_run: bool = False) -> str:
    """Write odoo_version.txt to the latest available image for `to_version`.

    Keeps the current edition (community/enterprise) and picks the newest
    release of the target major version — the same image-lookup mechanism
    `oops project update` uses for same-version refreshes
    (`services.docker.find_available_images`), but targeting a different
    (destination) major version instead of the current one.
    """
    try:
        current = parse_odoo_version(repo_path)
    except ValueError as exc:
        raise OopsError(f"Could not read current Odoo version from {config.project.file_odoo_version}.") from exc

    try:
        to_major = float(to_version)
    except ValueError as exc:
        raise OopsError(f"Invalid --to version: {to_version!r} (expected e.g. '19.0').") from exc

    try:
        images = find_available_images(version=to_major, enterprise=current.enterprise, release=None)
    except requests.RequestException as exc:
        raise APIError(f"Failed to fetch available images: {exc}") from exc

    if not images:
        raise OopsError(f"No Odoo image found for version {to_version}.")

    new_image = images[0].image
    if not dry_run:
        write_text_file(repo_path / config.project.file_odoo_version, [new_image])
    return new_image


def sync_project_files(repo_path: Path, dry_run: bool = False) -> "list[str]":
    """Sync project scaffolding from the configured remote (`oops project sync`).

    Degrades gracefully — returns `[]` without error when `sync.remote_url`
    isn't configured, since this is a bonus step inside a much larger
    destructive operation, not vanilla's primary purpose.
    """
    remote_url = config.sync.remote_url
    files = sorted(config.sync.files)
    if not remote_url or not files:
        return []
    if dry_run:
        return files

    with tempfile.TemporaryDirectory() as _tmpdir:
        tmpdir = Path(_tmpdir)
        fetch_project_files(remote_url, config.sync.branch, files, tmpdir)
        return copy_project_files(tmpdir, files, repo_path)


