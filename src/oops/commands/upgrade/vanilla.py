@command(name="vanilla", help=__doc__)
@click.option(
    "--from",
    "from_version",
    default=None,
    help="Source Odoo version (e.g. 18.0). Detected from odoo_version.txt/branch if omitted.",
)
@click.option(
    "--to",
    "to_version",
    default=None,
    help="Target Odoo version (e.g. 19.0). Required — the vanilla base is built on the destination version.",
)
@click.option("--branch", "branch_name", default=None, help="Branch to create (default: vanilla/<to_version>).")
@click.option("--dry-run", is_flag=True, help="Show what would happen, no git changes.")
@click.option("--no-commit", is_flag=True, help="Strip and generate the script, but do not commit.")
@click.option("-f", "--force", is_flag=True, help="Apply without prompting.")
@click.option("--format", "output_format", type=click.Choice(["text", "json"]), default="text", show_default=True)
@click.option("--output-path", type=click.Path(dir_okay=False, path_type=Path), default=None)
@click.pass_context
def main(  # noqa: C901
    ctx, from_version, to_version, branch_name, dry_run, no_commit, force, output_format, output_path
):
    """Strip non-core addons, bump to the target version, and generate an upgrade-util uninstall script."""
    warn_experimental()
    formatter: OutputFormatter = FORMATTERS[output_format]()
    metadata = get_metadata()
    repo, repo_path = require_repository()

    # Resolve from_version — the version modules are discovered/ordered/KB-checked against.
    if not from_version:
        from_version = config.manifest.odoo_version or ""
        if not from_version:
            try:
                from_version = str(parse_odoo_version(repo_path).major_version)
            except (ValueError, OSError):
                from_version = ""
        if not from_version:
            try:
                branch_probe = repo.active_branch.name
            except TypeError:
                branch_probe = ""
            match = re.search(r"\b(\d+\.\d+)\b", branch_probe)
            from_version = match.group(1) if match else ""
    if not from_version:
        raise OopsError(
            "Cannot detect source Odoo version. Provide --from (e.g. --from 18.0), "
            f"set manifest.odoo_version in .oops.yaml, or check {config.project.file_odoo_version}."
        )

    if not to_version:
        raise OopsError("Target version required. Provide --to (e.g. --to 19.0).")

    branch_name = branch_name or f"mig/{to_version}/vanilla"

    # `metadata.parameters` was snapshotted from raw CLI options before this
    # callback resolved from_version/to_version/branch_name — refresh it so
    # presenters see the actual values used, not the CLI defaults (None).
    if metadata is not None:
        metadata.parameters.update({"from_version": from_version, "to_version": to_version, "branch": branch_name})

    sub_meta_by_relpath = list_submodules(repo)

    with live_progress("Discovering non-core addons…"):
        addons = discover_non_core_addons(repo_path, sub_meta_by_relpath)

    if not addons and not sub_meta_by_relpath:
        raise OopsError("No non-core addons found and no submodules registered — nothing to strip.")

    with live_progress(f"Loading the global Odoo KB ({from_version})…"):
        kb_modules = load_odoo_kb(from_version)

    with live_progress(f"Resolving installed-module context ({config.project.file_installed_modules})…"):
        extra_depends, installed_warnings = load_installed_context(
            repo_path, addons, from_version, kb_modules=kb_modules
        )

    with live_progress("Computing safe removal order…"):
        modules = compute_removal_order(addons, extra_depends)

    with live_progress(f"Checking against the global Odoo KB ({from_version})…"):
        kb_checked, kb_warnings = flag_kb_collisions(modules, from_version, kb_modules=kb_modules)

    # Surface warnings now, before the strip plan is even presented — the
    # user must know collision detection was skipped (or what it found),
    # and whether the removal order is fully resolved or restricted to the
    # discovered-addon subgraph, while they can still decide not to proceed —
    # not only in the final summary after everything has already been
    # stripped/committed.
    warning_section(installed_warnings + kb_warnings)

    script_content = render_uninstall_script(modules)

    outer: Result[None] = Result()
    for w in installed_warnings + kb_warnings:
        outer.add_warning(w)

    rows = [[m.name, m.classification, str(m.load_index), m.matched_origin or ""] for m in modules]

    # Read-only (filesystem symlink walk + repo.submodules read) — safe to
    # build before the dry-run branch so --dry-run previews the orphan
    # sweep too, not only the addon-backed removals.
    plan, sub_by_relpath = build_strip_plan(repo, repo_path, modules)
    orphan_submodules = [a.label for a in plan.actionable if a.data.get("orphan")]
    for name in orphan_submodules:
        outer.add_warning(f"Submodule '{name}' has no discovered addon (never symlinked, or empty) — removed anyway.")

    if dry_run:
        with live_progress(f"Checking target image for {to_version}…"):
            preview_image = bump_odoo_version(repo_path, to_version, dry_run=True)
        preview_synced = sync_project_files(repo_path, dry_run=True)

        log.info(f"[dry-run] Would create branch {branch_name!r} from current HEAD.")
        for m in modules:
            flag = f" [{m.matched_origin}!]" if m.matched_origin else ""
            log.info(f"[dry-run] Would remove {m.name} (load_index={m.load_index}){flag}.")
        for name in orphan_submodules:
            log.info(f"[dry-run] Would remove orphan submodule {name!r} (no discovered addon).")
        containers = [config.submodules.current_path, *config.submodules.old_paths]
        log.info(f"[dry-run] Would remove any of {', '.join(str(p) for p in containers)} left empty afterward.")
        log.info(f"[dry-run] Would bump {config.project.file_odoo_version} to {preview_image!r}.")
        if preview_synced:
            log.info(f"[dry-run] Would sync project files: {', '.join(preview_synced)}.")
        else:
            log.info("[dry-run] sync.remote_url not configured — project sync would be skipped.")
        log.info(f"[dry-run] Would write {SCRIPT_REL_PATH}.")
        log.info(f"[dry-run] Would write {config.project.file_requirements} with the upgrade-util requirement.")
        log.info(f"[dry-run] Would ensure 'git' is listed in {config.project.file_packages}.")
        if not no_commit:
            log.info("[dry-run] Would commit.")

        result: "Result[dict]" = Result()
        result.data = {
            "cmd": f"Upgrade vanilla ({from_version} -> {to_version}, dry-run)",
            "dry_run": True,
            "rows": rows,
            "script_path": str(SCRIPT_REL_PATH),
            "branch": None,
            "image": preview_image,
            "synced_files": preview_synced,
            "kb_checked": kb_checked,
            "orphan_submodules": orphan_submodules,
        }
        result.merge(outer)
        output = VanillaPresenter().prepare(result, target=formatter.target, metadata=metadata)
        render_and_exit(result, formatter, output, output_format, output_path)
        return

    # Plan/order/KB-check were all computed above, against the source-version
    # tree exactly as it stood at the start of this run. Nothing has been
    # mutated yet — the branch is not created here either: `on_confirmed`
    # below only runs once the user has actually agreed to proceed (or
    # --force skipped the prompt), never on mere presentation of the plan.
    # `sub_by_relpath` was already computed once by `build_strip_plan` above.

    def apply(action: PlanAction) -> "tuple[str, bool]":
        return apply_strip_action(repo, repo_path, sub_by_relpath, action)

    def create_branch() -> None:
        if branch_name in {h.name for h in repo.heads}:
            raise OopsError(
                f"Branch {branch_name!r} already exists — pass --branch to use a different name, "
                "or delete/rename the existing branch first."
            )
        with live_progress(f"Creating branch {branch_name!r}…"):
            repo.git.checkout("-b", branch_name)

    run_mutation_workflow(
        plan=plan,
        apply=apply,
        outer=outer,
        title="Strip non-core addons",
        force=force,
        select=False,
        on_confirmed=create_branch,
        empty_message="Nothing to strip.",
    )

    if not outer.ok:
        # A per-action strip failure (`outer.add_error`, set by
        # `run_mutation_workflow`) must stop the run here: proceeding to
        # container cleanup, the version bump, project sync, script/
        # requirements writes, and the commit itself would silently bake a
        # partially-stripped tree into a "vanilla" base branch that claims
        # to be a full non-core wipe.
        outer.add_warning(
            f"Strip failed for one or more actions — branch {branch_name!r} left uncommitted for "
            "inspection. Fix the reported error(s) and re-run, or delete the branch and retry."
        )
        result: "Result[dict]" = Result()
        result.data = {
            "cmd": f"Upgrade vanilla ({from_version} -> {to_version})",
            "dry_run": False,
            "rows": rows,
            "script_path": str(SCRIPT_REL_PATH),
            "branch": None,
            "kb_checked": kb_checked,
            "orphan_submodules": orphan_submodules,
        }
        result.merge(outer)
        output = VanillaPresenter().prepare(result, target=formatter.target, metadata=metadata)
        render_and_exit(result, formatter, output, output_format, output_path)
        return

    with live_progress("Sweeping symlinks left broken by the strip…"):
        swept = sweep_broken_root_symlinks(repo, repo_path)
    for name in swept:
        outer.add_warning(f"Removed symlink {name!r}, left broken by the strip.")

    with live_progress("Cleaning up empty submodule container directories…"):
        removed_containers = cleanup_submodule_containers(repo_path)
    for name in removed_containers:
        log.info(f"Removed now-empty submodule container directory {name!r}.")

    with live_progress(f"Bumping to Odoo {to_version}…"):
        new_image = bump_odoo_version(repo_path, to_version)

    with live_progress("Syncing project scaffolding…"):
        synced_files = sync_project_files(repo_path)
    if not synced_files and config.sync.remote_url:
        outer.add_warning("Project sync configured but nothing was synced (no matching files found upstream).")
    elif not config.sync.remote_url:
        outer.add_warning("sync.remote_url not configured — project sync skipped.")

    write_uninstall_script(repo_path, script_content)
    ensure_upgrade_util_requirement(repo_path)
    ensure_git_package(repo_path)
    repo.git.add("-A")

    branch_ref = None
    if not no_commit:
        outer.merge(
            commit_v2(
                repo,
                repo_path,
                [],
                "vanilla_strip",
                from_version=from_version,
                to_version=to_version,
                skip_hooks=True,
                already_staged=True,
            )
        )
        if outer.ok:
            branch_ref = branch_name
    else:
        outer.add_warning("Don't forget to commit to share this vanilla base with the team.")

    report_path = artifact_path(repo_path, VANILLA_REPORT_FILE)
    save_vanilla_report(
        report_path,
        VanillaReport(
            from_version=from_version,
            to_version=to_version,
            modules=modules,
            script_path=str(SCRIPT_REL_PATH),
            branch=branch_ref,
            image=new_image,
            synced_files=synced_files,
            orphan_submodules=orphan_submodules,
            kb_checked=kb_checked,
        ),
    )

    final_result: "Result[dict]" = Result()
    final_result.data = {
        "cmd": f"Upgrade vanilla ({from_version} -> {to_version})",
        "dry_run": False,
        "rows": rows,
        "script_path": str(SCRIPT_REL_PATH),
        "branch": branch_ref,
        "image": new_image,
        "synced_files": synced_files,
        "report_path": str(report_path),
        "kb_checked": kb_checked,
        "orphan_submodules": orphan_submodules,
    }
    final_result.merge(outer)

    output = VanillaPresenter().prepare(final_result, target=formatter.target, metadata=metadata)
    render_and_exit(final_result, formatter, output, output_format, output_path)
