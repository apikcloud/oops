def build_strip_plan(repo: Repo, repo_path: Path, modules: "list[VanillaModule]") -> "tuple[Plan, dict]":
    """One PlanAction per addon: submodule-backed ones remove the submodule
    + its symlinks; root-level ("local") ones remove the addon directory.

    Modeled directly on `commands/submodules/remove.py:_build_plan`, extended
    to cover every addon rather than a user-selected subset, to handle
    root-level (non-submodule) addons, and — beyond what that command does —
    to guarantee every registered submodule is removed, not only the ones
    hosting a discovered addon:

    1. A submodule whose addon lives under a nested path (the common case,
       e.g. `.third-party/<org>/<repo>`) is matched via `rel_path`, exactly
       as before.
    2. A submodule checked out directly at the repo root has no nesting, so
       its addon's `rel_path` is `""` and step 1 cannot match it — it is
       instead matched by comparing the addon's own directory name
       (`dir_name`) against every submodule's `.path`. Without this, such a
       submodule is wrongly treated as a plain local directory: its files
       get `git rm -r`'d but its `.gitmodules`/`.git/config`/
       `.git/modules/<name>` entries are never cleaned up.
    3. After every discovered addon has been matched (or not), any
       remaining registered submodule — one with no discovered addon at
       all: never symlinked ("inactive"), genuinely addon-less, or not
       initialized on disk — gets its own removal action too. Every
       submodule must go, per this command's "full non-core wipe, no
       exceptions" contract; this mirrors the same "no referencing symlink
       → remove" rule `oops submodules prune` already applies on its own,
       generalized here to "no discovered addon at all → remove".

    Submodules are matched by `rel_path` (a Submodule's `.path`, the same key
    `services.git.list_submodules` uses and `Addon.rel_path` already carries)
    rather than by name: a submodule's `.name` is whatever it was created
    with — an "owner/repo" slug for one added via `oops submodules add`, but
    an arbitrary path for one added directly via `git submodule add` — so it
    cannot be reliably derived from itself and must not be used as a lookup key.

    Returns `(plan, sub_by_relpath)` — the caller reuses `sub_by_relpath`
    (a `Submodule.path -> Submodule` mapping) instead of rebuilding it from
    `repo.submodules` a second time.

    4. A submodule's activation symlinks are taken from the discovered addon
       list, not from a filesystem walk: `create_symlink` (io/file.py),
       `addons add` and `addons manage` all place an activation symlink at
       `<repo root>/<addon name>` and nowhere else, so an addon with
       `location == "active"` *is* its own link. `submodules remove` still
       needs the recursive `collect_symlink_paths`/`symlinks_into` pair
       because it removes a subset of submodules and must attribute each link
       to one of them; vanilla removes every submodule, so it has nothing to
       attribute. Not walking also means vanilla never sees a submodule's own
       internal `setup/<addon>/odoo/addons/<addon>` symlinks — tracked by the
       submodule's index, never the superproject's, so a `git rm` on one fails
       with "pathspec did not match any files".
    """
    sub_by_relpath = {s.path: s for s in repo.submodules}
    links_by_relpath: "dict[str, list[Path]]" = {}
    order: "list[str]" = []
    local_modules: "list[VanillaModule]" = []

    for m in modules:
        rel_path = m.rel_path if m.submodule and m.rel_path in sub_by_relpath else None
        if rel_path is None and m.dir_name in sub_by_relpath:
            rel_path = m.dir_name

        if rel_path is None:
            local_modules.append(m)
            continue

        if rel_path not in links_by_relpath:
            links_by_relpath[rel_path] = []
            order.append(rel_path)
        # `location == "active"` means symlinked at the repo root under the
        # addon's own name; the is_symlink() guard keeps a hand-made link
        # whose name differs from the addon directory's from being git rm'd
        # blind (it is then caught by the broken-link sweep instead).
        link = repo_path / m.name
        if m.location == "active" and link.is_symlink():
            links_by_relpath[rel_path].append(link)

    def submodule_action(rel_path: str, label: str, orphan: bool = False) -> PlanAction:
        links = links_by_relpath.get(rel_path, [])
        detail = f"submodule, {len(links)} symlink(s)"
        if orphan:
            detail += " — no discovered addon"
        return PlanAction(
            label=label,
            kind="available",
            detail=detail,
            data={"kind": "submodule", "rel_path": rel_path, "links": [str(lnk) for lnk in links], "orphan": orphan},
        )

    actions = [
        PlanAction(label=m.name, kind="available", detail="local addon directory", data={"kind": "local"})
        for m in local_modules
    ]
    actions += [submodule_action(rel_path, sub_by_relpath[rel_path].name) for rel_path in order]
    actions += [
        submodule_action(str(rel_path), sub.name, orphan=True)
        for rel_path, sub in sub_by_relpath.items()
        if rel_path not in links_by_relpath
    ]

    return Plan(title="Modules to strip", actions=actions), sub_by_relpath


def apply_strip_action(repo: Repo, repo_path: Path, sub_by_relpath: dict, action: PlanAction) -> "tuple[str, bool]":
    if action.data["kind"] == "submodule":
        remove_submodule(
            repo,
            repo_path,
            sub_by_relpath[action.data["rel_path"]],
            [Path(s) for s in action.data["links"]],
        )
    else:
        repo.git.rm("-r", "--force", "--", action.label)
    return "removed", True


def cleanup_submodule_containers(repo_path: Path) -> "list[str]":
    """Remove the submodule container directories left empty once every
    submodule has been stripped — `.third-party` (`config.submodules.current_path`)
    and any legacy container in `config.submodules.old_paths` (e.g. `third-party`).

    `Submodule.remove()` deletes each submodule's own directory but never
    touches its parent: git doesn't track empty directories at all, so a
    container (or an org-level subdirectory within it, e.g.
    `.third-party/OCA`) left with nothing but empty subdirectories after the
    last submodule under it is gone is pure filesystem residue, invisible to
    `git status`. Checked bottom-up, on the actual (live) directory contents
    rather than a precomputed listing, so a subdirectory just emptied by an
    earlier step of this same pass is correctly seen as empty by its parent.

    A container with any real leftover content (a non-submodule file
    committed there) is left untouched — only directories found genuinely
    empty are removed.
    """
    removed: "list[str]" = []
    for rel in [config.submodules.current_path, *config.submodules.old_paths]:
        container = repo_path / rel
        if not container.is_dir():
            continue
        for dirpath, _dirnames, _filenames in os.walk(container, topdown=False):
            p = Path(dirpath)
            if p != container and not any(p.iterdir()):
                p.rmdir()
        if not any(container.iterdir()):
            container.rmdir()
            removed.append(str(rel))
    return removed


def sweep_broken_root_symlinks(repo: Repo, repo_path: Path) -> "list[str]":
    """Drop root-level symlinks left pointing at nothing after the strip.

    Activation symlinks are derived from the discovered addon list, which can
    only see a link whose target still holds a readable manifest. A link that
    was already broken before the run — or one whose name differs from its
    target directory's — yields no addon, so nothing removes it, and
    `repo.git.add("-A")` will not either: a dangling symlink is still a valid
    `120000` blob. Left alone it would be committed into the vanilla base.

    `--ignore-unmatch` keeps an untracked link from raising; it is unlinked
    from disk afterwards either way.
    """
    removed: "list[str]" = []
    for entry in sorted(repo_path.iterdir()):
        if not entry.is_symlink() or entry.exists():
            continue
        repo.git.rm("--force", "--ignore-unmatch", "--", entry.name)
        if entry.is_symlink():
            entry.unlink()
        removed.append(entry.name)
    return removed


