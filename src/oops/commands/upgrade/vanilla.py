@command(name="vanilla", help=__doc__)
@click.option(
    "--from",
    "from_version",
    default=None,
    help="Source Odoo version (e.g. 18.0). Detected from odoo_version.txt/branch if omitted.",
)
@click.option("--branch", "branch_name", default=None, help="Branch to create (default: vanilla/<from_version>).")
@click.option("--tag", "tag_name", default=None, help="Tag to create (default: vanilla-<from_version>).")
@click.option("--dry-run", is_flag=True, help="Show what would happen, no git changes.")
@click.option("--no-commit", is_flag=True, help="Strip and generate the script, but do not commit or tag.")
@click.option("-f", "--force", is_flag=True, help="Apply without prompting.")
@click.option("--format", "output_format", type=click.Choice(["text", "json"]), default="text", show_default=True)
@click.option("--output-path", type=click.Path(dir_okay=False, path_type=Path), default=None)
@click.pass_context
def main(ctx, from_version, branch_name, tag_name, dry_run, no_commit, force, output_format, output_path):  # noqa: C901
    """Strip non-core addons and generate an upgrade-util uninstall script."""
    warn_experimental()
    formatter: OutputFormatter = FORMATTERS[output_format]()
    metadata = get_metadata()
    repo, repo_path = require_repository()

    # Resolve from_version.
    if not from_version:
        from_version = config.manifest.odoo_version or ""
        if not from_version:
            try:
                from_version = str(parse_odoo_version(repo_path).major_version)
            except (ValueError, OSError):
                from_version = ""
        if not from_version:
            try:
                branch_probe = repo.active_branch.name
            except TypeError:
                branch_probe = ""
            match = re.search(r"\b(\d+\.\d+)\b", branch_probe)
            from_version = match.group(1) if match else ""
    if not from_version:
        raise OopsError(
            "Cannot detect source Odoo version. Provide --from (e.g. --from 18.0), "
            f"set manifest.odoo_version in .oops.yaml, or check {config.project.file_odoo_version}."
        )

    branch_name = branch_name or f"vanilla/{from_version}"
    tag_name = tag_name or f"vanilla-{from_version}"

    # `metadata.parameters` was snapshotted from raw CLI options before this
    # callback resolved from_version/branch_name/tag_name — refresh it so
    # presenters see the actual values used, not the CLI defaults (None).
    if metadata is not None:
        metadata.parameters.update(
            {"from_version": from_version, "branch": branch_name, "tag": tag_name}
        )

    sub_meta_by_relpath = list_submodules(repo)

    with live_progress("Discovering non-core addons…"):
        addons = discover_non_core_addons(repo_path, sub_meta_by_relpath)

    if not addons:
        raise OopsError("No non-core addons found — nothing to strip.")

    with live_progress("Computing safe removal order…"):
        modules = compute_removal_order(addons)

    with live_progress(f"Checking against the global Odoo KB ({from_version})…"):
        kb_checked, kb_warnings = flag_kb_collisions(modules, from_version)

    script_content = render_uninstall_script(modules)

    outer: Result[None] = Result()
    for w in kb_warnings:
        outer.add_warning(w)

    rows = [[m.name, m.classification, str(m.load_index), m.matched_origin or ""] for m in modules]

    if dry_run:
        log.info(f"[dry-run] Would create branch {branch_name!r} from current HEAD.")
        for m in modules:
            flag = f" [{m.matched_origin}!]" if m.matched_origin else ""
            log.info(f"[dry-run] Would remove {m.name} (load_index={m.load_index}){flag}.")
        log.info(f"[dry-run] Would write {SCRIPT_REL_PATH}.")
        log.info(f"[dry-run] Would write {config.project.file_requirements} with the upgrade-util requirement.")
        log.info(f"[dry-run] Would ensure 'git' is listed in {config.project.file_packages}.")
        if not no_commit:
            log.info(f"[dry-run] Would commit and tag {tag_name!r}.")

        result: "Result[dict]" = Result()
        result.data = {
            "cmd": f"Upgrade vanilla ({from_version}, dry-run)",
            "dry_run": True,
            "rows": rows,
            "script_path": str(SCRIPT_REL_PATH),
            "branch": None,
            "tag": None,
            "kb_checked": kb_checked,
        }
        result.merge(outer)
        output = VanillaPresenter().prepare(result, target=formatter.target, metadata=metadata)
        render_and_exit(result, formatter, output, output_format, output_path)
        return

    with live_progress(f"Creating branch {branch_name!r}…"):
        repo.git.checkout("-b", branch_name)

    plan = build_strip_plan(repo, repo_path, modules)
    sub_by_relpath = {s.path: s for s in repo.submodules}

    def apply(action: PlanAction) -> "tuple[str, bool]":
        return apply_strip_action(repo, repo_path, sub_by_relpath, action)

    run_mutation_workflow(
        plan=plan,
        apply=apply,
        outer=outer,
        title="Strip non-core addons",
        force=force,
        select=False,
        empty_message="Nothing to strip.",
    )

    write_uninstall_script(repo_path, script_content)
    ensure_upgrade_util_requirement(repo_path)
    ensure_git_package(repo_path)
    repo.git.add("-A")

    branch_ref = None
    tag_ref = None
    if not no_commit:
        outer.merge(
            commit_v2(
                repo,
                repo_path,
                [],
                "vanilla_strip",
                from_version=from_version,
                skip_hooks=True,
                already_staged=True,
            )
        )
        if outer.ok:
            repo.create_tag(tag_name)
            branch_ref, tag_ref = branch_name, tag_name
    else:
        outer.add_warning("Don't forget to commit and tag to share this vanilla base with the team.")

    report_path = artifact_path(repo_path, VANILLA_REPORT_FILE)
    save_vanilla_report(
        report_path,
        VanillaReport(
            from_version=from_version,
            modules=modules,
            script_path=str(SCRIPT_REL_PATH),
            branch=branch_ref,
            tag=tag_ref,
            kb_checked=kb_checked,
        ),
    )

    final_result: "Result[dict]" = Result()
    final_result.data = {
        "cmd": f"Upgrade vanilla ({from_version})",
        "dry_run": False,
        "rows": rows,
        "script_path": str(SCRIPT_REL_PATH),
        "branch": branch_ref,
        "tag": tag_ref,
        "report_path": str(report_path),
        "kb_checked": kb_checked,
    }
    final_result.merge(outer)

    output = VanillaPresenter().prepare(final_result, target=formatter.target, metadata=metadata)
    render_and_exit(final_result, formatter, output, output_format, output_path)
